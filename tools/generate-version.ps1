param(
    [Parameter(Mandatory = $true)]
    [string]$RepositoryRoot,

    [Parameter(Mandatory = $true)]
    [string]$OutputPath,

    [Parameter(Mandatory = $true)]
    [string]$XexTemplatePath,

    [Parameter(Mandatory = $true)]
    [string]$XexOutputPath
)

$isShallow = & git -C $RepositoryRoot rev-parse --is-shallow-repository 2>$null
if ($LASTEXITCODE -ne 0 -or $isShallow -ne "false")
{
    throw "A complete Git history is required to determine the revision. Fetch the full history before building."
}

$gitRevision = & git -C $RepositoryRoot rev-list --count HEAD 2>$null
if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($gitRevision))
{
    throw "Could not determine the Git version for '$RepositoryRoot'."
}

# XEX versions have a 16-bit build field (major/minor are only 4 bits each).
$revision = 0
if (-not [int]::TryParse($gitRevision.Trim(), [ref]$revision) -or $revision -lt 1 -or $revision -gt 65535)
{
    throw "Git revision '$gitRevision' does not fit the XEX build field (1-65535)."
}

$gitHash = & git -C $RepositoryRoot rev-parse --short=8 HEAD 2>$null
if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($gitHash))
{
    throw "Could not determine the Git commit for '$RepositoryRoot'."
}

$releaseVersion = "r$($gitRevision.Trim())"

& git -C $RepositoryRoot diff-index --quiet HEAD -- 2>$null
$dirtyExitCode = $LASTEXITCODE
if ($dirtyExitCode -gt 1)
{
    throw "Could not determine the Git working tree state for '$RepositoryRoot'."
}

$exactTag = & git -C $RepositoryRoot describe --tags --exact-match --match $releaseVersion HEAD 2>$null
$isReleaseTag = $LASTEXITCODE -eq 0 -and $exactTag.Trim() -eq $releaseVersion
$isDirty = $dirtyExitCode -eq 1
$isCiRelease = $env:CODXE_RELEASE_BUILD -eq "1"

if ($isCiRelease -and $isDirty)
{
    throw "Refusing to create an official release version from a dirty working tree."
}

if (($isCiRelease -or $isReleaseTag) -and -not $isDirty)
{
    $gitVersion = $releaseVersion
}
else
{
    $gitVersion = "$releaseVersion-g$($gitHash.Trim())"
    if ($isDirty)
    {
        $gitVersion += "-dirty"
    }
}

# Native Git failures above are checked explicitly; generation errors must stop the build.
$ErrorActionPreference = 'Stop'

$escapedGitVersion = $gitVersion.Replace("\", "\\").Replace('"', '\"')
$header = "// Auto-generated by MSBuild. Do not edit.`r`n#pragma once`r`n`r`n#define GIT_VERSION `"$escapedGitVersion`"`r`n"

function Write-IfChanged([string]$Path, [string]$Content)
{
    $outputDirectory = [System.IO.Path]::GetDirectoryName($Path)
    [System.IO.Directory]::CreateDirectory($outputDirectory) | Out-Null

    if (-not [System.IO.File]::Exists($Path) -or [System.IO.File]::ReadAllText($Path) -ne $Content)
    {
        [System.IO.File]::WriteAllText($Path, $Content, [System.Text.Encoding]::UTF8)
    }
}

# Keep the checked-in configuration as the template; generated files live in IntDir.
$xex = New-Object System.Xml.XmlDocument
$xex.PreserveWhitespace = $true
$xex.Load($XexTemplatePath)
$version = $xex.SelectSingleNode('/xex/version')
if ($null -eq $version)
{
    $version = $xex.CreateElement('version')
    $xex.DocumentElement.AppendChild($version) | Out-Null
}
$version.SetAttribute('major', '0')
$version.SetAttribute('minor', '0')
$version.SetAttribute('build', $revision.ToString())
$version.SetAttribute('qfe', '0')

Write-IfChanged $OutputPath $header
Write-IfChanged $XexOutputPath $xex.OuterXml
Write-Host "GIT_VERSION=$gitVersion"
Write-Host "XEX_VERSION=0.0.$revision.0"
